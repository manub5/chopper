#!/usr/bin/env bash
#
# Easy installer for people outside the project.
#
# What it does:
#   1. Checks that we run on Linux.
#   2. Offers to install uv (Astral) if missing, after showing its location.
#   3. Offers missing ffmpeg / libportaudio2 packages via apt + sudo.
#   4. Syncs locked runtime dependencies (creates .venv, incl. CPU PyTorch).
#   5. Generates a friendly ./chopper launcher at the project root.
#   6. Offers a user-local KDE menu entry after showing its destination.
#
# It is meant to be run from the unpacked project folder:
#   ./install.sh
#
# Notes on effects (honest recap):
#   - May install uv under ~/.local/bin after confirmation, without editing profiles.
#   - May call sudo apt-get after confirmation (asks for your password).
#   - Downloads roughly 2 GB on the first run (CPU wheels of torch).
#   - uv may cache downloads and install Python under your account.
#   - Creates a generated ./chopper launcher next to this script.
#   - Creates/updates a Chopper menu entry only after confirmation.

set -euo pipefail

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
LAUNCHER="${PROJECT_DIR}/chopper"

info() { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33mwarning:\033[0m %s\n' "$*" >&2; }
die()  { printf '\033[1;31merror:\033[0m %s\n' "$*" >&2; exit 1; }

confirm() {
    local answer
    printf '%s [y/N] ' "$1"
    IFS= read -r answer || return 1
    case "${answer}" in
        y|Y|yes|YES) return 0 ;;
        *) return 1 ;;
    esac
}

check_launcher() {
    if [[ -L "${LAUNCHER}" ]] || { [[ -e "${LAUNCHER}" ]] &&
        { [[ ! -f "${LAUNCHER}" ]] ||
          ! grep -Fxq '# Generated by install.sh for Chopper.' "${LAUNCHER}"; }; }; then
        die "Refusing to overwrite an unrelated launcher: ${LAUNCHER}"
    fi
}

step_linux_check() {
    info "Checking operating system..."
    case "$(uname -s)" in
        Linux) ;;
        *) die "This installer supports Linux only (detected: $(uname -s))." ;;
    esac
}

ensure_command_line_tool() {
    if ! command -v curl >/dev/null 2>&1; then
        die "'curl' is required to download uv. Install it with: sudo apt-get install -y curl"
    fi
}

download_uv() (
    local installer
    installer="$(mktemp)" || die "Could not create a temporary file for the uv installer."
    trap 'rm -f -- "$installer"' EXIT
    curl -LsSf https://astral.sh/uv/install.sh -o "$installer" || die "Could not download uv; installer not executed."
    UV_INSTALL_DIR="${HOME}/.local/bin" UV_NO_MODIFY_PATH=1 sh "$installer" || die "uv installation failed."
)

step_uv() {
    info "Checking for uv..."
    if command -v uv >/dev/null 2>&1; then
        info "uv already installed ($(uv --version))."
        return
    fi
    ensure_command_line_tool
    info "uv is missing. Its official installer will be downloaded from https://astral.sh."
    info "It will install uv in ${HOME}/.local/bin without changing your shell profiles."
    confirm "Download and install uv there?" || die "uv installation declined. No uv files installed."
    download_uv
    export PATH="${HOME}/.local/bin:${PATH}"
    command -v uv >/dev/null 2>&1 || die "uv installation failed: binary not found on PATH."
    info "uv installed ($(uv --version))."
}

need_apt_package() {
    dpkg -s "$1" >/dev/null 2>&1
}

step_system_packages() {
    info "Checking for system packages (ffmpeg, libportaudio2)..."
    if ! command -v apt-get >/dev/null 2>&1; then
        warn "apt-get not found. Skipping. Make sure 'ffmpeg' and 'libportaudio2' are installed."
        return
    fi

    local missing=()
    need_apt_package ffmpeg        || missing+=("ffmpeg")
    need_apt_package libportaudio2 || missing+=("libportaudio2")

    if [[ ${#missing[@]} -eq 0 ]]; then
        info "System packages already present."
        return
    fi

    if ! command -v sudo >/dev/null 2>&1; then
        die "Missing packages: ${missing[*]}. Install them manually (sudo needed): sudo apt-get install -y ${missing[*]}"
    fi

    info "About to install missing packages with sudo: ${missing[*]}"
    confirm "Update apt package lists and install these system packages?" || die "System package installation declined."
    sudo apt-get update
    sudo apt-get install -y "${missing[@]}"
    info "System packages installed."
}

step_uv_sync() {
    info "Setting up the Python environment in ${PROJECT_DIR}/.venv (roughly 2 GB on first install)..."
    info "uv may cache downloads and install Python under your account; existing extra packages are kept."
    ( cd "${PROJECT_DIR}" && UV_PROJECT_ENVIRONMENT="${PROJECT_DIR}/.venv" uv sync --project "${PROJECT_DIR}" --locked --no-dev --inexact )
    [[ -x "${PROJECT_DIR}/.venv/bin/chopper" ]] || die "Environment incomplete: Chopper executable missing. Run bash install.sh again."
    info "Environment ready."
}

step_launcher() {
    check_launcher
    info "Writing the launcher: ./chopper"
    cat > "${LAUNCHER}" <<'EOF'
#!/usr/bin/env bash
# Generated by install.sh for Chopper.
set -euo pipefail
DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
if [[ ! -x "${DIR}/.venv/bin/chopper" ]]; then
    printf '%s\n' 'Chopper environment is missing. Run bash install.sh from the application folder.' >&2
    exit 1
fi
cd "${DIR}"
exec "${DIR}/.venv/bin/chopper" "$@"
EOF
    chmod +x "${LAUNCHER}"
}

main() {
    step_linux_check
    check_launcher
    step_uv
    step_system_packages
    step_uv_sync
    step_launcher
    "${PROJECT_DIR}/.venv/bin/python" "${PROJECT_DIR}/scripts/install_desktop.py" --launcher "${LAUNCHER}"

    printf '\n'
    info "Done. Start the software with:"
    printf '    %s\n' "./chopper"
}

main "$@"
